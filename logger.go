package main

import (
	"fmt"
	"os"
	"time"
)

func CreateLogger() {
	LogFile, LogFileCreateError = os.Create("log.txt")
	if LogFileCreateError != nil {
		fmt.Println("ERROR: could initialze a logger: ", LogFileCreateError)
		return
	}
	logFile, err := os.OpenFile("log.txt", os.O_RDWR, 0644)
	if err != nil {
		fmt.Println("ERROR: could not open log.txt file: ", err)
		return
	}
	customLayout := "2006-January-02 15:04:05"
	n, err := logFile.Write([]byte(time.Now().Format(customLayout) + ": This file was auto generated by 4tress\n"))
	_ = n
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Println("Initialized logger successfully")
}

func Log(message string) {
	logFile, err := os.OpenFile("log.txt", os.O_WRONLY|os.O_APPEND, 0644)
	if err != nil {
		fmt.Println("Could not log to the log file: ", err)
		return
	}
	customLayout := "2006-January-02 15:04:05"
	t := time.Now().Format(customLayout)
	_ = t

	n, err := logFile.Write([]byte(t + ": " + message + "\n"))
	_ = n
	if err != nil {
		fmt.Println("ERROR: could not write to log file: ", err)
		return
	}
}
